import { ChangeDetectionStrategy, Component, computed, inject } from '@angular/core';
import { SupervisionStore } from '../../../core/state/supervision.store';
import { EmptyState } from '../../../shared/components/empty-state/empty-state';
import { Icon } from '../../../shared/components/icon/icon';
import { Member } from '../../../shared/components/member/member';
import { Panel } from '../../../shared/components/panel/panel';
import { RelativeTimePipe } from '../../../shared/pipes/relative-time.pipe';
import { REPORT_KIND } from '../../../shared/utils/presentation';

@Component({
  selector: 'app-reports-widget',
  imports: [Panel, Icon, Member, EmptyState, RelativeTimePipe],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    <ui-panel heading="Recent reports" subheading="Generated by agents, reviewed by people" [flush]="true">
      <ul>
        @for (report of reports(); track report.id) {
          <li class="list-row report">
            <span class="report__icon"><ui-icon name="file" [size]="15" /></span>
            <div class="list-row__body">
              <span class="list-row__title">{{ report.title }}</span>
              <span class="list-row__meta">{{ report.summary }}</span>
              <span class="report__meta">
                <span class="chip">{{ kinds[report.kind] }}</span>
                <ui-member [ref]="report.authorRef" size="xs" />
                <span class="report__time">{{ report.createdAt | relativeTime }}</span>
              </span>
            </div>
          </li>
        } @empty {
          <ui-empty-state [compact]="true" icon="file" heading="No reports yet" />
        }
      </ul>
    </ui-panel>
  `,
  styles: `
    .report {
      align-items: flex-start;
    }
    .report__icon {
      display: inline-flex;
      padding: 7px;
      border-radius: var(--radius-md);
      background: var(--color-info-subtle);
      color: var(--color-info);
    }
    .report__meta {
      display: flex;
      align-items: center;
      flex-wrap: wrap;
      gap: var(--space-2);
      margin-top: var(--space-1-5);
    }
    .report__time {
      color: var(--color-text-tertiary);
      font-size: var(--text-xs);
    }
  `,
})
export class ReportsWidget {
  private readonly supervision = inject(SupervisionStore);
  protected readonly kinds = REPORT_KIND;
  protected readonly reports = computed(() => this.supervision.reports().slice(0, 4));
}
